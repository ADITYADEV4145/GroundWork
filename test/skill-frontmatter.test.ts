import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, describe, expect, it } from 'vitest';
import { parse } from 'yaml';
import { applySetup, planSetup } from '../src/setup/apply.js';
import { targetsFor } from '../src/setup/targets.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const dirs: string[] = [];
const temp = () => {
  const dir = mkdtempSync(path.join(os.tmpdir(), 'gw-skill-frontmatter-'));
  dirs.push(dir);
  return dir;
};
afterEach(() => dirs.splice(0).forEach((dir) => rmSync(dir, { recursive: true, force: true })));

function skills(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (['.git', 'node_modules', '.groundwork'].includes(entry.name)) return [];
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) return skills(file);
    return entry.name === 'SKILL.md' ? [file] : [];
  });
}

function expectSkill(text: string, label: string): void {
  const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(text);
  expect(frontmatter, `${label}: YAML frontmatter is required`).not.toBeNull();
  // A real YAML parser rejects the unquoted `repository: to find code` regression.
  const metadata = parse(frontmatter![1]!) as Record<string, unknown>;
  for (const key of ['name', 'description']) {
    expect(metadata?.[key], `${label}: ${key}`).toBeTypeOf('string');
    expect((metadata[key] as string).trim(), `${label}: ${key} is nonempty`).not.toBe('');
  }
}

describe('skill frontmatter', () => {
  it('parses the canonical skill and any other repository SKILL.md copies', () => {
    const files = skills(root);
    expect(files).toContain(path.join(root, 'SKILL.md'));
    for (const file of files) expectSkill(readFileSync(file, 'utf8'), path.relative(root, file));
  });

  it('parses every skill actually generated by agent setup, including Codex', () => {
    const project = temp();
    applySetup(project, planSetup(project, targetsFor({ root: project, gw: 'gw' }), 'add'), 'add');
    const files = skills(project);
    expect(files).toContain(path.join(project, '.agents/skills/groundwork/SKILL.md'));
    for (const file of files) expectSkill(readFileSync(file, 'utf8'), path.relative(project, file));
  });

  it('parses the skill files shipped with the npm/Claude plugin package', () => {
    const destination = temp();
    const packed = JSON.parse(execFileSync('npm', ['pack', '--json', '--offline', '--ignore-scripts', '--pack-destination', destination], { cwd: root, encoding: 'utf8' })) as { filename: string }[];
    expect(packed).toHaveLength(1);
    const archive = path.join(destination, packed[0]!.filename);
    const files = execFileSync('tar', ['-tf', archive], { encoding: 'utf8' }).split('\n').filter((file) => /(?:^|\/)SKILL\.md$/.test(file));
    expect(files).toContain('package/SKILL.md');
    for (const file of files) expectSkill(execFileSync('tar', ['-xOf', archive, file], { encoding: 'utf8' }), file);
  });
});
