import { execFileSync } from 'node:child_process';
import { lstatSync, readdirSync, readFileSync, realpathSync, existsSync } from 'node:fs';
import path from 'node:path';
import ignore from 'ignore';
import picomatch from 'picomatch';
import type { GroundworkConfig } from '../config/schema.js';
import { INDEXED_EXTENSIONS, languageForPath } from '../lang/parser.js';
import { GW_DIR, toPosix } from '../util/paths.js';

const ALWAYS_SKIP_DIRS = new Set(['node_modules', 'bin', 'obj', 'target', 'out', '.gradle', 'vendor', '.git', GW_DIR, 'dist', 'build', '.next', '__pycache__', '.venv', 'venv', '.tox', 'coverage']);

function gitFiles(root: string, paths?: string[]): string[] | null {
  if (!process.env.GIT_DIR) {
    let dir = path.resolve(root);
    while (!existsSync(path.join(dir, '.git'))) {
      const parent = path.dirname(dir);
      if (parent === dir) return null;
      dir = parent;
    }
  }
  try {
    const out = execFileSync('git', ['ls-files', '-co', '--exclude-standard', '-z', ...(paths ? ['--', ...paths] : [])], {
      cwd: root,
      stdio: ['ignore', 'pipe', 'ignore'],
      maxBuffer: 256 * 1024 * 1024,
    });
    return out.toString('utf8').split('\0').filter(Boolean);
  } catch {
    return null;
  }
}

function walkFiles(root: string, paths?: string[]): string[] {
  const ig = ignore();
  const gi = path.join(root, '.gitignore');
  if (existsSync(gi)) ig.add(readFileSync(gi, 'utf8'));
  const out: string[] = [];
  if (paths) {
    for (const candidate of new Set(paths)) {
      const rel = toPosix(candidate);
      const parts = rel.split('/');
      if (path.isAbsolute(rel) || parts.some((part) => !part || part === '.' || part === '..') || ig.ignores(rel)) continue;
      try {
        if (parts.slice(0, -1).some((_, i) => !lstatSync(path.join(root, ...parts.slice(0, i + 1))).isDirectory())) continue;
        const st = lstatSync(path.join(root, rel));
        if (st.isFile() || st.isSymbolicLink()) out.push(rel);
      } catch { /* Missing files and non-directory ancestors are not candidates. */ }
    }
    return out;
  }
  const rec = (dir: string) => {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const abs = path.join(dir, e.name);
      const rel = toPosix(path.relative(root, abs));
      if (e.isDirectory()) {
        if (ALWAYS_SKIP_DIRS.has(e.name) || ig.ignores(rel + '/')) continue;
        rec(abs);
      } else if ((e.isFile() || e.isSymbolicLink()) && !ig.ignores(rel)) out.push(rel);
    }
  };
  rec(root);
  return out;
}

/** Repo-relative POSIX paths of every candidate source file (git-aware; honours .gitignore and config globs). */
export function discoverFiles(root: string, config: GroundworkConfig, paths?: string[]): string[] {
  const all = gitFiles(root, paths) ?? walkFiles(root, paths);
  const include = config.index.include.length ? picomatch(config.index.include, { dot: true }) : null;
  const exclude = config.index.exclude.length ? picomatch(config.index.exclude, { dot: true }) : null;
  const exts = new Set(INDEXED_EXTENSIONS);
  const realRoot = realpathSync(root);
  const out: string[] = [];
  for (const rel of all) {
    const p = toPosix(rel);
    if (p.split('/').some((seg) => ALWAYS_SKIP_DIRS.has(seg))) continue;
    const ext = path.extname(p).toLowerCase();
    if (!exts.has(ext) || !languageForPath(p)) continue;
    if (include && !include(p)) continue;
    if (exclude && exclude(p)) continue;
    const abs = path.join(root, p);
    try {
      const st = lstatSync(abs);
      if (st.isSymbolicLink()) {
        const target = realpathSync(abs);
        if (target !== realRoot && !target.startsWith(realRoot + path.sep)) continue;
      } else if (!st.isFile()) continue;
    } catch {
      continue; // deleted from the work tree but still in the git index
    }
    out.push(p);
  }
  return out.sort();
}

export function makeTestMatcher(config: GroundworkConfig): (p: string) => boolean {
  return picomatch(config.index.testGlobs, { dot: true });
}

const GENERATED_MARKERS = /@generated|DO NOT EDIT|auto-generated|autogenerated|Code generated by/i;

/** Minified bundles and files marked generated are indexed as files but not parsed for symbols. */
export function looksGenerated(p: string, content: string): boolean {
  if (/\.min\.(js|mjs|cjs)$/.test(p) || /(^|\/)(vendor|generated|__generated__)\//.test(p) || /_pb2\.py$|\.pb\.(ts|js)$/.test(p)) return true;
  if (GENERATED_MARKERS.test(content.slice(0, 600))) return true;
  const lines = content.split('\n', 50);
  const long = lines.filter((l) => l.length > 1000).length;
  return long > 0 && content.length / Math.max(1, content.split('\n').length) > 500;
}
